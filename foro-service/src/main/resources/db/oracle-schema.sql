CREATE SEQUENCE CATEGORIA_SEQ START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE PUBLICACION_SEQ START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE COMENTARIO_SEQ START WITH 1 INCREMENT BY 1;

CREATE TABLE CATEGORIAS (
    ID NUMBER(19) PRIMARY KEY,
    NOMBRE VARCHAR2(80 CHAR) NOT NULL UNIQUE
);

CREATE TABLE PUBLICACIONES (
    ID NUMBER(19) PRIMARY KEY,
    TITULO VARCHAR2(150 CHAR) NOT NULL,
    CONTENIDO VARCHAR2(4000 CHAR) NOT NULL,
    CATEGORIA_ID NUMBER(19) NOT NULL,
    AUTOR_ID NUMBER(19) NOT NULL,
    FECHA_CREACION TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT FK_PUBLICACION_CATEGORIA FOREIGN KEY (CATEGORIA_ID) REFERENCES CATEGORIAS(ID)
);

CREATE TABLE COMENTARIOS (
    ID NUMBER(19) PRIMARY KEY,
    CONTENIDO VARCHAR2(2000 CHAR) NOT NULL,
    PUBLICACION_ID NUMBER(19) NOT NULL,
    AUTOR_ID NUMBER(19) NOT NULL,
    FECHA_CREACION TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT FK_COMENTARIO_PUBLICACION FOREIGN KEY (PUBLICACION_ID) REFERENCES PUBLICACIONES(ID)
);

CREATE INDEX IDX_PUBLICACION_CATEGORIA ON PUBLICACIONES(CATEGORIA_ID);
CREATE INDEX IDX_PUBLICACION_TITULO ON PUBLICACIONES(TITULO);
CREATE INDEX IDX_COMENTARIO_PUBLICACION ON COMENTARIOS(PUBLICACION_ID);
